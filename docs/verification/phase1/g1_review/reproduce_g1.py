"""G1 independent-review entry point (criterion 122). Read-only: writes no files.

Run from the repository root on a clean checkout of the reviewed commit:

    python docs/verification/phase1/g1_review/reproduce_g1.py

1. Checks every calculation file against implementation_manifest.json, so the
   reviewer knows the code is the version that was reviewed.
2. Reproduces the 20 designated reference cases (12 native methods, 3
   supplemental estimators, 2 legacy residence routes) from independently
   specified expected values. No expected value is generated by the code under review.
3. Runs the Phase 1 reference, bridge-method (M1.6), unit and error-state test files.

Supersedes method_acceptance/evidence/reproduce.py, whose manifest predates the
TRACE01 version metadata and therefore no longer matches main. That script and
its manifest are kept unchanged as historical evidence.
"""
import hashlib, json, math, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).parent
sys.path.insert(0, str(ROOT))

manifest = json.loads((HERE / "implementation_manifest.json").read_text(encoding="utf-8"))
changed = [n for n, d in manifest.items()
           if not (ROOT / n).exists() or hashlib.sha256((ROOT / n).read_bytes()).hexdigest() != d]
if changed:
    raise SystemExit("Reviewed source version differs: " + ", ".join(changed))
print(len(manifest), "calculation files match the reviewed version")

from backend.engineering_sizing.registry import calculate
from backend.orchestration.sizing import derive_size
from backend.equipment_costing.unit_conversion import convert, identify_unit
from backend.equipment_costing.unit_conversion.bridges import liquid, mechanical, production_sizing

def cv(value, unit, target=None):
    if value == "quantity":
        return identify_unit(unit).quantity
    c = convert(value, unit, target)
    if c.value is None:
        raise ValueError("; ".join(c.issues))
    return c.value

native = json.loads((ROOT / "backend/tests/fixtures/sizing_verification/references.json").read_text(encoding="utf-8"))
extra = json.loads((ROOT / "docs/verification/phase1/method_acceptance/evidence/additional_references.json").read_text(encoding="utf-8"))
count = 0
for c in native + extra:
    mid, inputs = c["method"], c.get("parameters", c.get("inputs"))
    if mid == "vessel_mass":
        result = mechanical.evaluate(inputs)
    elif mid == "vessel_productivity":
        result = production_sizing.vessel_productivity(inputs)
    elif mid == "mixing_power":
        result = liquid.evaluate(mid, c["value"], c["source_unit"], inputs, cv)
    elif mid in {"mass_residence", "volume_residence"}:
        prop = "mass_flow" if mid == "mass_residence" else "volume_flow"
        report = {"entities": [{"key": "s", "values": [{"id": "ref", "property": prop,
                  "normalized_value": c["value"], "normalized_unit": c["source_unit"], "status": "verified"}]}]}
        result = derive_size({"sizing": {"method": mid, "stream_key": "s", **inputs}}, report)
    else:
        result = calculate(mid, c["value"], inputs)
    rel = c.get("relative_tolerance", c.get("rtol")); ab = c.get("absolute_tolerance", c.get("atol"))
    assert result[1] == c["unit"] and math.isclose(result[0], float(c["expected"]), rel_tol=rel, abs_tol=ab), (mid, result, c["expected"])
    print(c.get("id", mid), result[0], result[1], "PASS (bounded reference)")
    count += 1
print(count, "designated reference cases reproduced")

tests = ["backend/tests/test_sizing_independent_verification.py", "backend/tests/test_method_acceptance.py",
         "backend/tests/test_bridge_method_references.py", "backend/tests/test_sizing_error_states.py",
         "backend/tests/test_legacy_sizing_boundaries.py", "backend/tests/test_unit_acceptance.py",
         "backend/tests/test_unit003_active_conversions.py", "backend/tests/test_native_boolean_safety.py",
         "backend/tests/test_engineering_method_versions.py"]
sys.exit(subprocess.call([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", *tests], cwd=ROOT))
